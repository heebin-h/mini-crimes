const ALL_CASES = [...SEASON_1, ...SPECIAL];

/** /api/cases 응답용 — answer 제거, choices correct 플래그 제거 후 포함 */
function casesForClient() {
  return ALL_CASES.map(({ answer, id, ...rest }) => {
    const raw = CHOICES[id] ?? {};
    const choices = Object.fromEntries(
      Object.entries(raw).map(([qid, list]) => [
        qid,
        list.map(({ correct: _, ...c }) => c),
      ])
    );
    return { id, ...rest, choices };
  });
}

/** 서버 채점용 */
function getCaseAnswer(caseId) {
  return ALL_CASES.find(c => c.id === caseId)?.answer ?? null;
}

/** 서버 채점용 — 정답 선택지 id 포함 (correct 플래그 있음) */
function getChoices(caseId) {
  return CHOICES[caseId] ?? null;
}

/** 케이스 존재 확인 */
function caseExists(caseId) {
  return ALL_CASES.some(c => c.id === caseId);
}

module.exports = { ALL_CASES, casesForClient, getCaseAnswer, getChoices, caseExists };
